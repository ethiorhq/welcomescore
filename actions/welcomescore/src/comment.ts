export const COMMENT_MARKER = "<!-- welcomescore-audit-comment -->";

export type PrCommentContext = {
  repoOwner: string;
  repoName: string;
  pullNumber: number;
  token: string;
};

export type CommentReportData = {
  score: number;
  grade: string;
  reportUrl: string;
  nextUsefulMove?: {
    title: string;
    expectedOutcome: string;
    effort: string;
  } | null;
  checksSummary: {
    passed: number;
    total: number;
  };
};

export function buildPrCommentMarkdown(data: CommentReportData): string {
  const moveSection = data.nextUsefulMove
    ? `### Next Useful Move: **${data.nextUsefulMove.title}**\n\n> ${data.nextUsefulMove.expectedOutcome} *(Effort: ${data.nextUsefulMove.effort})*\n`
    : "";

  return `${COMMENT_MARKER}
## 🌟 WelcomeScore Contributor Readiness Report

**Score: ${data.score}/100 (Grade ${data.grade})** · *${data.checksSummary.passed}/${data.checksSummary.total} checks passing*

${moveSection}
[View Full Evidence Report ↗](${data.reportUrl})

---
*Generated by [WelcomeScore Action](https://welcomescore.vercel.app). Point-in-time public audit.*
`;
}

export async function upsertPrComment(
  context: PrCommentContext,
  body: string,
): Promise<{ success: boolean; commentId?: number; error?: string }> {
  const { repoOwner, repoName, pullNumber, token } = context;
  const baseUrl = `https://api.github.com/repos/${encodeURIComponent(repoOwner)}/${encodeURIComponent(repoName)}`;
  const headers = {
    Accept: "application/vnd.github+json",
    Authorization: `Bearer ${token}`,
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": "welcomescore-action",
  };

  try {
    // 1. Fetch existing issue comments
    const commentsRes = await fetch(`${baseUrl}/issues/${pullNumber}/comments`, {
      headers,
    });

    if (!commentsRes.ok) {
      return {
        success: false,
        error: `Failed to fetch comments: HTTP ${commentsRes.status}`,
      };
    }

    const comments = (await commentsRes.json()) as Array<{
      id: number;
      body?: string;
    }>;
    const existing = comments.find((c) => c.body?.includes(COMMENT_MARKER));

    if (existing) {
      // 2. Update existing comment idempotently
      const updateRes = await fetch(`${baseUrl}/issues/comments/${existing.id}`, {
        method: "PATCH",
        headers,
        body: JSON.stringify({ body }),
      });

      if (!updateRes.ok) {
        return {
          success: false,
          error: `Failed to update comment: HTTP ${updateRes.status}`,
        };
      }

      return { success: true, commentId: existing.id };
    }

    // 3. Post new comment
    const createRes = await fetch(`${baseUrl}/issues/${pullNumber}/comments`, {
      method: "POST",
      headers,
      body: JSON.stringify({ body }),
    });

    if (!createRes.ok) {
      return {
        success: false,
        error: `Failed to create comment: HTTP ${createRes.status}`,
      };
    }

    const created = (await createRes.json()) as { id: number };
    return { success: true, commentId: created.id };
  } catch (err) {
    return {
      success: false,
      error: err instanceof Error ? err.message : "Unknown error",
    };
  }
}
