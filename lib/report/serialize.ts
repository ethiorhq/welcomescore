import type { WelcomeScoreReport } from "./types";
import { assertValidReport } from "./schema";

export function serializeReportToJson(
  report: WelcomeScoreReport,
  pretty = true,
): string {
  return `${JSON.stringify(report, null, pretty ? 2 : undefined)}\n`;
}

export function safeParseReportJson(jsonText: string): WelcomeScoreReport {
  let parsed: unknown;
  try {
    parsed = JSON.parse(jsonText);
  } catch (error) {
    throw new Error(
      `Malformed JSON: ${error instanceof Error ? error.message : "Parse error"}`,
    );
  }
  return assertValidReport(parsed);
}

const STATUS_ICONS: Record<string, string> = {
  pass: "✓ PASS",
  partial: "~ PARTIAL",
  missing: "✗ MISSING",
  unknown: "? UNKNOWN",
};

export function serializeReportToMarkdown(report: WelcomeScoreReport): string {
  const lines: string[] = [
    `# WelcomeScore Audit Report: ${report.repository.fullName}`,
    "",
    `> Evidence-based contributor readiness evaluation generated at ${report.analyzedAt}.`,
    "",
    "## Summary",
    "",
    "| Dimension | Value |",
    "|---|---|",
    `| **Repository** | [${report.repository.fullName}](${report.publicLinks.repository}) |`,
    `| **Score** | **${report.score}/100** |`,
    `| **Grade** | **${report.grade}** |`,
    `| **Default Branch** | \`${report.repository.defaultBranch}\` |`,
  ];

  if (report.analyzedCommit) {
    lines.push(`| **Analyzed Commit** | \`${report.analyzedCommit.slice(0, 7)}\` |`);
  }

  lines.push(
    `| **Coverage** | ${report.coverage.percentage}% (${report.coverage.observed}/${report.coverage.possible} checks observed) |`,
    `| **Schema Version** | \`v${report.schemaVersion}\` (tool \`v${report.toolVersion}\`) |`,
    `| **Public Report** | [View Report](${report.publicLinks.report}) |`,
    "",
  );

  if (report.nextUsefulMove) {
    const move = report.nextUsefulMove;
    lines.push(
      "## Next Useful Move",
      "",
      `### ${move.title}`,
      "",
      `**Effort Band:** \`${move.effort}\`  `,
      `**Expected Outcome:** ${move.expectedOutcome}`,
      "",
      `**Why It Matters:**  \n${move.whyItMatters}`,
      "",
      "**Acceptance Criteria:**",
      ...move.acceptanceCriteria.map((c) => `- [ ] ${c}`),
      "",
    );

    if (move.suggestedFiles && move.suggestedFiles.length > 0) {
      lines.push(
        "**Suggested Files:**",
        ...move.suggestedFiles.map((file) => `- \`${file}\``),
        "",
      );
    }

    if (move.issueDraft) {
      lines.push(
        "<details>",
        "<summary><strong>Suggested Issue Draft</strong> (click to expand)</summary>",
        "",
        `**Title:** \`${move.issueDraft.title}\`  `,
        `**Labels:** ${move.issueDraft.labels.map((l) => `\`${l}\``).join(", ")}`,
        "",
        "```markdown",
        move.issueDraft.body,
        "```",
        "</details>",
        "",
      );
    }

    if (move.patchPlan) {
      lines.push(
        "<details>",
        `<summary><strong>Patch Plan (${move.patchPlan.safety})</strong></summary>`,
        "",
        `**Target Files:** ${move.patchPlan.files.map((f) => `\`${f}\``).join(", ")}`,
        "",
        "**Operations:**",
        ...move.patchPlan.operations.map((op) => `- ${op}`),
        "",
        "</details>",
        "",
      );
    }
  }

  lines.push(
    "## Evidence Breakdown",
    "",
    "| Check | Category | Status | Points | Explanation | Confidence |",
    "|---|---|:---:|:---:|---|:---:|",
  );

  for (const check of report.checks) {
    const statusText = STATUS_ICONS[check.status] || check.status;
    const pointsText = `${check.points}/${check.maxPoints}`;
    const escapedExplanation = check.explanation.replace(/\|/g, "\\|");
    const labelLink = check.sourceUrl
      ? `[${check.label}](${check.sourceUrl})`
      : check.label;
    lines.push(
      `| ${labelLink} | ${check.category} | ${statusText} | ${pointsText} | ${escapedExplanation} | ${check.confidence} |`,
    );
  }

  lines.push("");

  if (report.goodFirstIssues.length > 0) {
    lines.push("## Starter Issues for New Contributors", "");
    for (const issue of report.goodFirstIssues) {
      lines.push(`- [${issue.title}](${issue.url})`);
    }
    lines.push("");
  }

  lines.push("## Limitations & Privacy", "");
  for (const limitation of report.limitations) {
    lines.push(`- ${limitation}`);
  }
  lines.push("");

  lines.push(
    "---",
    `*Report generated by [WelcomeScore](${report.publicLinks.report}). Evidence badge: \`![WelcomeScore](${report.publicLinks.badge})\`*`,
    "",
  );

  return lines.join("\n");
}
